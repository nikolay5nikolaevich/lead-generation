# --- Схемы ответов. Уходят в `claude -p --json-schema`, ответ проверяется ими же.

class SearchQueries(BaseModel):
    queries: list[str]


class ExtractedFacts(BaseModel):
    facts: list[Fact]


class Rating(BaseModel):
    # Обоснование раньше оценки: модель сначала рассуждает, потом ставит число.
    reasoning: str
    rating: Literal[0, 1, 2, 3]


# Поля — ключи RUBRIC_WEIGHTS (проверяет тест): схема сама требует оценку
# по каждому критерию, и модель не может придумать свой.
class RubricRatings(BaseModel):
    industry: Rating
    size: Rating
    region: Rating
    need: Rating


class DraftEmail(BaseModel):
    text: str


class Claim(BaseModel):
    claim: str
    # Номера фактов из списка в промпте. Пустой список — опоры нет.
    fact_ids: list[int]


class DraftClaims(BaseModel):
    claims: list[Claim]


# --- Промпты

def plan_queries_prompt(icp_text: str, count: int) -> str:
    return f"""Описание идеального клиента (ICP):
<icp>
{icp_text}
</icp>

Составь поисковые запросы для веб-поиска, ровно {count} шт., по которым в выдаче окажутся сайты
самих компаний, подходящих под ICP. Не сайты-каталоги, агрегаторы, новости или вакансии.

Запрос — фраза, которую подходящая компания сама пишет на своём сайте о признаке из ICP:
в новостях, анонсах, на странице о компании, от первого лица («наша компания примет участие…»,
«приглашаем посетить наш стенд…», «мы поставляем продукцию в…»). По таким фразам поиск приводит
на страницы самих компаний. Не описывай признак со стороны и не пиши словами того, что мы предлагаем:
по ним находятся те, кто пишет о признаке или продаёт вокруг него услуги, — посредники, консультанты,
центры поддержки, организаторы и СМИ.
Запросы должны различаться: разные признаки из ICP, разные страны или регионы, разные формулировки.

Запросы на языке региона из ICP, как их набрал бы человек в поисковике: 4–8 слов,
без кавычек и операторов."""


FACT_KINDS = """- what_they_do — чем компания занимается, основные услуги или продукты;
- size — размер: число сотрудников, площадь складов, число филиалов, оборот;
- industry — отрасль и специализация;
- clients — клиенты, отрасли клиентов, известные заказчики;
- hook — конкретная деталь, за которую можно зацепиться в письме: новый склад,
  расширение, сертификация, внедрение системы, заметное достижение;
- tech_stack — системы и технологии, которыми компания пользуется (WMS, 1С, ТСД и т. п.)."""


def extract_facts_prompt(icp_text: str, domain: str, pages: dict[str, str]) -> str:
    pages_text = "\n\n".join(f'<page url="{url}">\n{text}\n</page>' for url, text in pages.items())
    return f"""Ниже тексты страниц сайта {domain}. Извлеки факты о компании, которые помогут
оценить её по ICP и написать ей персональное письмо.

<icp>
{icp_text}
</icp>

{pages_text}

Виды фактов (поле kind):
{FACT_KINDS}

Правила:
- quote — дословная цитата со страницы: скопируй фрагмент текста символ в символ,
  без пересказа, сокращений и исправлений опечаток. Одно предложение или его часть.
- source_url — url той страницы из <page>, где стоит цитата, в точности как в атрибуте.
- value — суть факта своими словами, коротко.
- Только то, что прямо написано на странице. Не делай выводов и не додумывай.
- Если факта какого-то вида на страницах нет — не включай его. Фактов нет совсем —
  верни пустой список. Это нормальный ответ.
- Не больше 10 фактов, самые полезные для оценки и письма."""


RUBRIC = {
    "industry": "отрасль и специализация компании совпадают с ICP",
    "size": "размер компании (сотрудники, площади, филиалы) попадает в диапазон из ICP",
    "region": "компания работает в регионе из ICP",
    "need": "есть признаки потребности в нашем предложении из ICP",
}


def _facts_block(facts: list[Fact]) -> str:
    if not facts:
        return "(фактов нет)"
    return "\n".join(f"- [{fact.kind}] {fact.value} (цитата: «{fact.quote}», источник: {fact.source_url})" for fact in facts)


def rate_criteria_prompt(icp_text: str, domain: str, facts: list[Fact]) -> str:
    criteria = "\n".join(f"- {name}: {description}" for name, description in RUBRIC.items())
    return f"""Оцени, насколько компания {domain} подходит под ICP, по каждому критерию рубрики.

<icp>
{icp_text}
</icp>

Факты о компании, собранные с её сайта:
{_facts_block(facts)}

Критерии:
{criteria}

Шкала для каждого критерия:
- 3 — факты прямо показывают соответствие;
- 2 — скорее соответствует: есть косвенные признаки;
- 1 — фактов для оценки нет или соответствие сомнительно;
- 0 — факты показывают, что компания не соответствует.

Опирайся только на перечисленные факты. В reasoning одним-двумя предложениями
назови факт, на котором основана оценка, или скажи, что фактов нет."""


def draft_email_prompt(
    icp_text: str, domain: str, facts: list[Fact], previous_draft: str, unsupported_claims: list[str]
) -> str:
    rewrite = ""
    if unsupported_claims:
        claims = "\n".join(f"- {claim}" for claim in unsupported_claims)
        rewrite = f"""

Это переписывание. Предыдущий черновик:
<draft>
{previous_draft}
</draft>

В нём есть утверждения о компании, которых нет в фактах:
{claims}

Перепиши письмо: убери эти утверждения или замени их тем, что прямо сказано в цитатах фактов.
Не добавляй новых утверждений о компании, которых нет в цитатах, в том числе предположений
о её трудностях."""
    return f"""Напиши черновик первого холодного письма компании {domain} от нашего имени.
Что мы предлагаем и кому — в ICP.

<icp>
{icp_text}
</icp>

Факты о компании:
{_facts_block(facts)}

Требования:
- 60–120 слов, на «вы», деловой и живой тон, без канцелярита.
- Первая фраза — про компанию: опирается на один конкретный факт из списка (лучше hook).
- О компании — только то, что есть в фактах. Не выдумывай цифры, имена, события.
- Одно-два предложения о нашем предложении — только то, что сказано о нём в ICP, ничего не добавляя.
  Не связывай его с компанией выводами («значит, вам…», «логично», «для компании с таким опытом»):
  это утверждения о компании, которых нет в фактах.
- В конце — простой вопрос или предложение короткого созвона.
- Без темы письма, подписи, плейсхолдеров вроде [Имя] и спам-слов
  («уникальное предложение», «только сегодня», «бесплатно»).{rewrite}"""


def extract_claims_prompt(domain: str, draft: str, facts: list[Fact]) -> str:
    # Только цитаты: их validate_facts сверил с сайтом, а пересказ модели (value) бывает шире цитаты.
    numbered = "\n".join(f"{number}. «{fact.quote}»" for number, fact in enumerate(facts, 1))
    return f"""Ниже черновик письма компании {domain} и пронумерованный список цитат с её сайта.
Выпиши из письма все утверждения о компании-получателе и для каждого укажи номера цитат,
которые его подтверждают.

<draft>
{draft}
</draft>

Цитаты:
{numbered or "(цитат нет)"}

Утверждение о компании — всё, что письмо сообщает или предполагает о ней: чем она
занимается, размер, цифры, клиенты, события, технологии, её задачи и трудности,
в том числе предположения («наверняка», «как и многие склады», «вы, вероятно»).
Не выписывай рассказ о нас и нашем предложении, приветствие, вопросы и предложение созвониться.

Правила:
- claim — фрагмент письма с утверждением, дословно.
- fact_ids — номера цитат, в которых сказано то же самое. Цитата не подтверждает утверждение,
  если оно обобщает, округляет или добавляет то, чего в цитате нет.
- Подходящей цитаты нет — пустой fact_ids. Это нормальный ответ."""
